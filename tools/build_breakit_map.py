#!/usr/bin/env python3
"""
Semantic map for "Break It, Fix It" (docs/break-it/map.js).

One UMAP of all 539 bank items, both traits together, from their OpenAI
text-embedding-3-small vectors (cosine metric). The Construct Lab map was drawn per
trait; this one keeps both traits in one space, so items from the other trait land in
their own region and a dropped facet leaves an empty one. A large min_dist spreads each
facet's cloud so that the scale's items do not sit on top of each other.

The 12 mood items were written for this lab and were never embedded, so they have no
position; the app lists them beside the map instead of guessing where they would sit.

Run: python3 tools/build_breakit_map.py
"""
import csv, json, os
import numpy as np
import pyreadr, rdata, umap

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, "data")
SOURCES = [
    ("claude-sonnet-4-6", "items_claude_sonnet_4_6_iteration_308.rds", "embeds.claude.RDS"),
    ("gpt-4o", "items_gpt_4o_iteration_050.rds", "embeds4.o.RDS"),
    ("gpt-5.4", "items_gpt_5_4_iteration_079.rds", "embeds5.4.RDS"),
]
vec = {}
for llm, fi, fe in SOURCES:
    df = list(pyreadr.read_r(os.path.join(D, fi)).values())[0]
    E = rdata.read_rds(os.path.join(D, fe))["embeddings"]
    ids = [str(x) for x in E.coords["dim_1"].values]
    assert ids == [str(int(i)) for i in df.ID]
    M = np.asarray(E.values, dtype=float).T
    for j, sid in enumerate(df.ID.astype(int)):
        vec[(llm, int(sid))] = M[j] / np.linalg.norm(M[j])

items = list(csv.DictReader(open(os.path.join(D, "items.csv"), encoding="utf-8")))
codes = [r["code"] for r in items]
X = np.vstack([vec[(r["llm"], int(r["source_id"]))] for r in items])
U = umap.UMAP(n_neighbors=30, min_dist=0.9, spread=1.0, metric="cosine", random_state=11).fit_transform(X)
U = (U - U.min(0)) / (U.max(0) - U.min(0))
out = {c: [round(float(x), 4), round(float(y), 4)] for c, (x, y) in zip(codes, U)}
path = os.path.join(ROOT, "docs", "break-it", "map.js")
with open(path, "w", encoding="utf-8") as fh:
    fh.write("/* Break It, Fix It semantic map: UMAP (cosine, n_neighbors 30, min_dist .9) of the\n"
             "   text-embedding-3-small vectors of the 539 bank items, both traits together.\n"
             "   Generated by tools/build_breakit_map.py. */\n")
    fh.write("window.BREAK_MAP = "); json.dump(out, fh, separators=(",", ":")); fh.write(";\n")
print("wrote", path, os.path.getsize(path) // 1024, "KB")
